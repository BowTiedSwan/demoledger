/**
 * Generates REPO_MAP.md: every non-ignored source file with its exported symbols.
 * Never edit REPO_MAP.md by hand; run `pnpm repo-map` (or `pnpm repo-map --check` to detect drift).
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'REPO_MAP.md');

const SECTIONS: ReadonlyArray<{ prefix: string; title: string }> = [
  { prefix: 'packages/shared/', title: 'packages/shared — contracts (zod schemas, types, pure helpers)' },
  { prefix: 'packages/db/', title: 'packages/db — schema, migrations, roles, seed' },
  { prefix: 'apps/api/', title: 'apps/api — Hono API, auth, repo, AI flow' },
  { prefix: 'apps/web/', title: 'apps/web — Vite + React SPA' },
  { prefix: 'evals/', title: 'evals — guard and model evals' },
  { prefix: 'scripts/', title: 'scripts' },
  { prefix: '', title: 'root' },
];

const SKIP = [/^pnpm-lock\.yaml$/, /^REPO_MAP\.md$/, /\/migrations\/meta\//, /\.(png|jpg|svg|ico|woff2?)$/];
const CODE = /\.(ts|tsx)$/;

function listFiles(): string[] {
  const out = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard'], {
    cwd: ROOT,
    encoding: 'utf8',
  });
  return out
    .split('\n')
    .filter((f) => f !== '' && !SKIP.some((re) => re.test(f)))
    .sort();
}

/** Exported names, in source order, via conservative regexes (no TS compiler dependency). */
export function exportsOf(source: string): string[] {
  const names: string[] = [];
  const decl =
    /^export\s+(?:declare\s+)?(?:default\s+)?(?:async\s+)?(function\*?|const|let|class|interface|type|enum)\s+([A-Za-z0-9_$]+)/gm;
  for (const m of source.matchAll(decl)) {
    const kind = m[1] === 'function*' ? 'function' : m[1];
    names.push(`${m[2]} (${kind})`);
  }
  const list = /^export\s+(?:type\s+)?\{([^}]*)\}(?:\s+from\s+['"]([^'"]+)['"])?/gm;
  for (const m of source.matchAll(list)) {
    for (const raw of (m[1] ?? '').split(',')) {
      const part = raw.trim().replace(/^type\s+/, '');
      if (!part) continue;
      const alias = part.split(/\s+as\s+/).pop() ?? part;
      names.push(m[2] ? `${alias} (re-export)` : alias);
    }
  }
  for (const m of source.matchAll(/^export\s+\*\s+(?:as\s+(\w+)\s+)?from\s+['"]([^'"]+)['"]/gm)) {
    names.push(m[1] ? `${m[1]} (namespace of ${m[2]})` : `* from ${m[2]}`);
  }
  if (/^export\s+default\s+(?!function|class|async)/m.test(source)) names.push('default');
  return names;
}

export function render(files: string[], read: (f: string) => string): string {
  const lines = [
    '# REPO_MAP',
    '',
    '<!-- GENERATED by scripts/repo-map.ts. Do not edit; run `pnpm repo-map`. -->',
    '',
    'Every non-ignored file, grouped by package, with the exported symbols of each TypeScript module.',
    'Tests are listed by file; open them for case names.',
    '',
  ];
  const seen = new Set<string>();
  for (const { prefix, title } of SECTIONS) {
    const group = files.filter(
      (f) =>
        !seen.has(f) &&
        (prefix === ''
          ? !f.includes('/') || f.startsWith('.') || f.startsWith('docker/') || f.startsWith('docs/')
          : f.startsWith(prefix)),
    );
    if (group.length === 0) continue;
    lines.push(`## ${title}`, '');
    for (const f of group) {
      seen.add(f);
      const isTest = /\.test\.tsx?$/.test(f);
      const ex = CODE.test(f) && !isTest ? exportsOf(read(f)) : [];
      lines.push(ex.length > 0 ? `- \`${f}\` — ${ex.join(', ')}` : `- \`${f}\`${isTest ? ' (test)' : ''}`);
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function main(): void {
  const content = render(listFiles(), (f) => readFileSync(join(ROOT, f), 'utf8'));
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {
      // missing file counts as drift
    }
    if (current !== content) {
      console.error('REPO_MAP.md is stale. Run `pnpm repo-map`.');
      process.exit(1);
    }
    console.log('REPO_MAP.md is up to date.');
    return;
  }
  writeFileSync(OUT, content);
  console.log(`wrote REPO_MAP.md (${content.split('\n').length} lines)`);
}

main();
